    top10_holder_pct FLOAT8 DEFAULT 0.0,
    honeypot_check_passed BOOLEAN DEFAULT true,
    dev_holding_pct FLOAT8 DEFAULT 0.0,
    sniper_bundle_pct FLOAT8 DEFAULT 0.0,
    instant_scalp_flags_count INT4 DEFAULT 0,
    filter_pass BOOLEAN NOT NULL,
    rejection_reason TEXT,
    raw_check_data JSONB DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_filter_results_token ON public.filter_results (token_address);

