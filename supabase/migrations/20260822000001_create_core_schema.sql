-- 1. WALLETS (Track deployers and flagged wallets)
CREATE TABLE IF NOT EXISTS public.wallets (
    wallet_address VARCHAR(64) PRIMARY KEY,
    first_seen TIMESTAMPTZ DEFAULT now(),
    reputation_score FLOAT8 DEFAULT 0.0,
    rug_count_history INT4 DEFAULT 0,
    total_tokens_launched INT4 DEFAULT 0,
    tags JSONB DEFAULT '[]'::jsonb
);

-- 2. TOKENS (Ingested tokens from Pump.fun and Raydium)
CREATE TABLE IF NOT EXISTS public.tokens (
    token_address VARCHAR(64) PRIMARY KEY,
    symbol VARCHAR(32),
    name VARCHAR(128),
    deployer_wallet_address VARCHAR(64) REFERENCES public.wallets(wallet_address) ON DELETE SET NULL,
    launch_timestamp TIMESTAMPTZ DEFAULT now(),
    launch_venue VARCHAR(32) NOT NULL,
    status VARCHAR(32) DEFAULT 'INGESTED'::character varying,
    initial_metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_tokens_launch_time ON public.tokens (launch_timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_tokens_status ON public.tokens (status);

